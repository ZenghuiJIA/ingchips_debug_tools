import { ref } from 'vue';

export type LocaleType = 'zh' | 'zh-TW' | 'en';

const LOCALE_STORAGE_KEY = 'ai_hil_app_locale';

function detectInitialLocale(): LocaleType {
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem(LOCALE_STORAGE_KEY);
    if (saved === 'zh' || saved === 'zh-TW' || saved === 'en') {
      return saved;
    }
  }
  if (typeof navigator !== 'undefined' && navigator.language) {
    const lang = navigator.language.toLowerCase();
    if (lang.startsWith('zh-tw') || lang.startsWith('zh-hk') || lang.startsWith('zh-mo') || lang.includes('hant')) {
      return 'zh-TW';
    }
    if (lang.startsWith('zh')) {
      return 'zh';
    }
    return 'en';
  }
  return 'zh';
}

export const currentLocale = ref<LocaleType>(detectInitialLocale());

export function setLocale(lang: LocaleType) {
  currentLocale.value = lang;
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem(LOCALE_STORAGE_KEY, lang);
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang === 'zh-TW' ? 'zh-Hant' : lang === 'zh' ? 'zh-Hans' : 'en';
  }
}

